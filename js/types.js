export function typeEffectiveness(moveType, defenderTypes, opts = {}) {
  let mult = 1;
  for (const def of defenderTypes) {
    let m = CHART[moveType]?.[def] ?? 1;
    // フリーズドライ: みずにも抜群
    if (opts.freezeDry && def === "みず") m = 2;
    // フライングプレス: かくとう×ひこうの合成は呼び出し側で処理
    mult *= m;
  }
  return mult;
}

export function effectivenessLabel(mult) {
  if (mult === 0) return "効果がない";
  if (mult >= 4) return "効果はばつぐん！（4倍）";
  if (mult >= 2) return "効果はばつぐん！";
  if (mult === 1) return "効果は普通（等倍）";
  if (mult <= 0.25) return "効果はいまひとつ…（1/4）";
  if (mult < 1) return "効果はいまひとつ…";
  return "";
}
